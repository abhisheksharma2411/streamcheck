#!/usr/bin/env python3
"""Generate the gap column of the live-execution table from results/e3_live.json.

The gap is wall clock measured against a real broker, so it moves between
machines and between runs on one machine. It was hand-copied into the
manuscript once and went stale at the next reproduction, which nothing caught:
check_prose_numbers.py skips tabular environments by construction, and
verify_claims.py guards the mechanism (which runs clear the lifetime) rather
than the printed durations.

So generate the rows. `--check` fails if the manuscript disagrees with the
results, which is the gate that was missing.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TEX = ROOT / "paper" / "streamcheck.tex"
RESULTS = ROOT / "results" / "e3_live.json"

BEGIN = "% BEGIN generated by scripts/make_live_table.py -- do not edit by hand"
END = "% END generated by scripts/make_live_table.py"

#: printed name and grouping, in the order the table presents them. The groups
#: are the paper's three behaviours: charges twice as configured, charges twice
#: everywhere, charges once everywhere.
ROWS: tuple[tuple[str, str], ...] = (
    ("SC101", "key lifetime below horizon"),
    ("SC102", "state TTL below horizon"),
    ("SC105", "retry window above lifetime"),
    (None, None),
    ("SC001", "effect not idempotent"),
    ("SC002", "non-deterministic key"),
    ("SC003", "missing key"),
    (None, None),
    ("SC006", "effect before dedup"),
    ("SC103", "transaction timeout"),
)

ARMS = ("defective", "control", "sufficient")


def charges(runs: list[dict], rule: str, arm: str) -> int:
    """Distinct charges the arm produced, as the table's def./inf/suf columns."""
    vals = {r[arm]["charges"] for r in runs if r["rule"] == rule}
    if len(vals) != 1:
        raise SystemExit(
            f"{rule}/{arm}: the runs disagree on the charge count ({sorted(vals)}). "
            "The table prints one number per cell, so this needs a decision, "
            "not a silently chosen value."
        )
    return vals.pop()


def gap(runs: list[dict], rule: str) -> str:
    secs = sorted(
        r[arm]["observed_gap_ms"] / 1000.0
        for r in runs
        for arm in ARMS
        if r["rule"] == rule
    )
    if not secs:
        raise SystemExit(f"{rule}: no runs in {RESULTS.name}")
    lo, hi = f"{secs[0]:.1f}", f"{secs[-1]:.1f}"
    return lo if lo == hi else f"{lo}--{hi}"


def body() -> str:
    runs = json.loads(RESULTS.read_text())["runs"]
    out = []
    for rule, label in ROWS:
        if rule is None:
            out.append(r"\midrule")
            continue
        cells = " & ".join(str(charges(runs, rule, a)) for a in ARMS)
        out.append(f"{rule} & {label} & {gap(runs, rule)} & {cells} \\\\")
    return "\n".join(out)


def splice(tex: str, generated: str) -> str:
    pattern = re.compile(
        re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL
    )
    if not pattern.search(tex):
        raise SystemExit(
            f"{TEX.name}: the generated-table markers are missing. Expected\n"
            f"  {BEGIN}\n  ...\n  {END}\n"
            "A scripted edit that cannot find its anchor must fail, not "
            "silently write nothing."
        )
    # a lambda, not a replacement string: the generated rows are LaTeX and
    # re.sub reads backslashes in the replacement as group escapes.
    return pattern.sub(lambda _: f"{BEGIN}\n{generated}\n{END}", tex, count=1)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail if the manuscript disagrees with results/")
    args = ap.parse_args(argv)

    tex = TEX.read_text()
    generated = body()
    updated = splice(tex, generated)

    if args.check:
        if updated != tex:
            sys.stderr.write(
                "the live-execution table in the manuscript does not match "
                f"{RESULTS.name}.\n\nresults/ say:\n\n{generated}\n\n"
                "Run `make tables` and rebuild.\n"
            )
            return 1
        print(f"live-execution table matches {RESULTS.name}")
        return 0

    if updated == tex:
        print(f"live-execution table already matches {RESULTS.name}")
        return 0
    TEX.write_text(updated)
    print(f"live-execution table regenerated from {RESULTS.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
